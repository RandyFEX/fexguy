// Minimal .xlsx writer (no dependencies): inline strings, numbers, formulas
// with cached values, bold headers, number formats, column widths, frozen
// header rows and filters. Enough for the rate workbook; not a general library.
import { deflateRawSync } from 'node:zlib';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
export const col = (n) => {
  let s = '';
  for (n += 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
};
export const ref = (c, r) => `${col(c)}${r + 1}`;

// Style ids (see styles below): 0 normal, 1 bold, 2 money, 3 rate 0.00,
// 4 bold title, 5 factor 0.000000, 6 wrapped text, 7 bold money.
